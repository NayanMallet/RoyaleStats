#!/usr/bin/env node
// Checks that a commit message follows the convention of .github/CONTRIBUTING.md:
//   <emoji> <type>(<scope>): <subject>
// Called by the Husky commit-msg hook with the path of the message file.
const fs = require('fs');

const TYPES = [
  'build',
  'ci',
  'docs',
  'feat',
  'views',
  'db',
  'fix',
  'perf',
  'refactor',
  'style',
  'test',
  'types',
  'version',
  'other',
];

const EMOJI = String.raw`(?::[a-z0-9_+-]+:|\p{Extended_Pictographic}[\p{Extended_Pictographic}️‍]*)`;
const PATTERN = new RegExp(
  String.raw`^${EMOJI}\s+(${TYPES.join('|')})(\([\w./@-]+\))?!?: \S.*$`,
  'u',
);
// Messages generated by Git itself are accepted as is.
const GIT_GENERATED = /^(Merge |Revert "|fixup! |squash! |amend! )/;

const file = process.argv[2];
if (!file) {
  console.error('Usage: node scripts/check-commit-msg.cjs <commit-message-file>');
  process.exit(2);
}

const lines = fs
  .readFileSync(file, 'utf8')
  .split('\n')
  .filter((line) => !line.startsWith('#'));
const header = lines.find((line) => line.trim() !== '');

// Markers that make GitHub skip the CI workflows. The same list is enforced on
// pull requests by .github/workflows/no-skip-ci.yml.
const SKIP_CI =
  /\[\s*(skip\s+ci|ci\s+skip|no\s+ci|skip\s+actions|actions\s+skip)\s*\]|skip-checks\s*:\s*true/i;
const skipLine = lines.find((line) => SKIP_CI.test(line));
if (skipLine) {
  console.error(`
✖ Message de commit refusé : marqueur de saut de CI interdit.
    ${skipLine.trim()}

  La CI doit tourner sur chaque commit. Retirez [skip ci], [ci skip], [no ci],
  [skip actions], [actions skip] ou skip-checks: true du message.
`);
  process.exit(1);
}

if (!header || GIT_GENERATED.test(header) || PATTERN.test(header)) {
  process.exit(0);
}

console.error(`
✖ Message de commit invalide :
    ${header}

  Format attendu : <emoji> <type>(<portée>): <sujet>
  Exemple       : ✨ feat(front): ajoute la page 404
  Types         : ${TYPES.join(', ')}

  Voir .github/CONTRIBUTING.md#nommer-les-commits
`);
process.exit(1);
